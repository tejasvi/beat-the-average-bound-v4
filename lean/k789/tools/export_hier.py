#!/usr/bin/env python3
"""Export a hierarchical certificate (k = 8 or k = 9) of C_6.39 and the extension trees (levels 4..7) to Lean data
modules.

Usage: python3 -I export_hier.py CERT.json TREEDIR MODNAME OUTDIR [CHUNK]
Writes OUTDIR/<MODNAME>/Trees.lean (levels), OUTDIR/<MODNAME>/Blocks.lean (blocks and constants) and
OUTDIR/<MODNAME>.lean (imports). With CHUNK > 0, block lists longer than CHUNK are written as concatenations of
definitions of at most CHUNK blocks (long list literals exceed the elaborator's recursion depth). Big natural numbers
are written with nat_b64% (little-endian base64). Nothing in the
data is trusted by the Lean proofs; the leaves of the trees are recomputed by replaying the tree walk (signs only).
"""
import sys, os, json, math, base64, hashlib
sys.set_int_max_str_digits(0)
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from export_direct import tuples_of, replay_leaves, pack, zig


def b64(n):
    if n < 2 ** 64:
        return str(n)
    b = n.to_bytes((n.bit_length() + 7) // 8, 'little')
    return f'(nat_b64% "{base64.b64encode(b).decode()}")'


def pblock(b):
    t, m = b['t'], b['m']
    nTm = len(tuples_of(m)) if m >= 4 else 0
    flags = []
    for bits, J in b['flags']:
        assert len(bits) == nTm
        bv = sum(1 << i for i, ch in enumerate(bits) if ch == '1')
        jm = sum(1 << j for j in J)
        flags.append(bv | (jm << nTm))
    n = len(flags)
    maxz = 1
    for wn, wd, v in b['sos']['terms']:
        assert len(v) == n and wn >= 0
        maxz = max(maxz, max(zig(z) for z in v))
    wv = maxz.bit_length()
    terms = ', '.join(f'({wn}, {b64(pack([zig(z) for z in v], wv))})' for wn, wd, v in b['sos']['terms'])
    return f'⟨{t}, {m}, {n}, {nTm}, {b64(pack(flags, nTm + m))}, {wv}, [{terms}]⟩'


def main():
    certfn, treedir, mod, outdir = sys.argv[1:5]
    chunk = int(sys.argv[5]) if len(sys.argv) > 5 else 0
    cert = json.load(open(certfn))
    K = cert['K']
    sha = hashlib.sha256(open(certfn, 'rb').read()).hexdigest()
    os.makedirs(f'{outdir}/{mod}', exist_ok=True)
    # trees
    lines = ['import BeatAvg.Core.Chain', 'import BeatAvg.Load', '',
             f'/-! Extension trees, levels 4-7 (generated by tools/export_hier.py; certificate sha256 {sha}). -/', '',
             'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', '', f'namespace BeatAvg.Data.{mod}', 'open BeatAvg.Check', '']
    parents = [0]
    names = []
    for k in range(4, 8):
        trees = json.load(open(f'{treedir}/trees_{k}.json'))
        assert len(trees) == len(parents)
        nT = len(tuples_of(k))
        recs = []
        newp = []
        for P, (perm, tokens) in zip(parents, trees):
            leaves = replay_leaves(k, P, perm, tokens)
            newp += leaves
            assert max(tokens) < 1024 and max(perm) < 256
            recs.append(f'⟨{b64(P)}, {b64(pack(perm, 8))}, {len(perm)}, {b64(pack(tokens, 10))}, {nT}, '
                        f'{b64(pack(leaves, nT))}, {len(leaves)}⟩')
        names.append(f'recs{k}')
        lines.append(f'def recs{k} : List PRec := [\n  ' + ',\n  '.join(recs) + ']\n')
        parents = newp
        print(f'level {k}: {len(trees)} trees, {len(parents)} patterns', file=sys.stderr)
    lines.append('def levels : List (List TreeRec) := [' + ', '.join(f'{n}.map PRec.unpackR' for n in names) + ']')
    lines.append(f'end BeatAvg.Data.{mod}')
    open(f'{outdir}/{mod}/Trees.lean', 'w').write('\n'.join(lines) + '\n')
    # blocks
    lower, mid, top = [], [], []
    wds, vdens = set(), set()
    for b in cert['blocks']:
        t, m = b['t'], b['m']
        for wn, wd, v in b['sos']['terms']:
            wds.add(wd)
        vdens.add(b['sos']['den'])
        if 2 * m - t <= 7:
            lower.append(b)
        elif (t, m) == (6, 7):
            mid.append(b)
        else:
            assert (t, m) == (7, 8) and K == 9
            top.append(b)
    assert len(wds) == 1 and len(vdens) == 1
    qscale = wds.pop() * vdens.pop() ** 2
    den7 = len(tuples_of(7))
    for b in lower:
        t, m = b['t'], b['m']
        D = math.comb(7, t) * math.comb(7 - t, m - t) * math.comb(7 - m, m - t)
        den7 = den7 * (D * qscale) // math.gcd(den7, D * qscale)
    lines = ['import BeatAvg.Core.Hier', 'import BeatAvg.Load', '',
             f'/-! Blocks of the certificate (generated by tools/export_hier.py; certificate sha256 {sha}). -/', '',
             'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', '', f'namespace BeatAvg.Data.{mod}', 'open BeatAvg.Check', '']
    for name, bl in (('lowerP', lower), ('midP', mid), ('topP', top)):
        if chunk > 0 and len(bl) > chunk:
            parts = []
            for c in range(0, len(bl), chunk):
                pn = f'{name}{c // chunk}'
                parts.append(pn)
                lines.append(f'def {pn} : List PBlock := [\n  ' + ',\n  '.join(pblock(b) for b in bl[c:c + chunk]) + ']\n')
            lines.append(f'def {name} : List PBlock := ' + ' ++ '.join(parts) + '\n')
        else:
            lines.append(f'def {name} : List PBlock := [\n  ' + ',\n  '.join(pblock(b) for b in bl) + ']\n')
    lines.append('def lower : List DBlock := lowerP.map PBlock.unpackB')
    lines.append('def mid : List DBlock := midP.map PBlock.unpackB')
    lines.append('def top : List DBlock := topP.map PBlock.unpackB')
    nT = {8: len(tuples_of(8)), 9: len(tuples_of(9))}

    def excl(key, kk):
        out = []
        for bits, crt in cert.get(key, []):
            assert len(bits) == nT[kk]
            bv = sum(1 << i for i, ch in enumerate(bits) if ch == '1')
            out.append(f'({b64(bv)}, [' + ', '.join(f'({r}, {mlt})' for r, mlt in crt) + '])')
        return '[' + ', '.join(out) + ']'
    if K == 8:
        lines.append(f'def excl8 : List (Nat × List (Nat × Nat)) := {excl("excluded", 8)}')
    else:
        lines.append(f'def excl8 : List (Nat × List (Nat × Nat)) := {excl("excluded8", 8)}')
        lines.append(f'def excl9 : List (Nat × List (Nat × Nat)) := {excl("excluded9", 9)}')
        lines.append(f'def capN : Nat := {cert["cap"][0]}\ndef capD : Nat := {cert["cap"][1]}')
    lines.append(f'def lamN : Nat := {cert["claimed"][0]}\ndef lamD : Nat := {cert["claimed"][1]}')
    lines.append(f'def den7 : Nat := {den7}\ndef qscale : Nat := {qscale}')
    lines.append(f'end BeatAvg.Data.{mod}')
    open(f'{outdir}/{mod}/Blocks.lean', 'w').write('\n'.join(lines) + '\n')
    open(f'{outdir}/{mod}.lean', 'w').write(f'import BeatAvg.Data.{mod}.Trees\nimport BeatAvg.Data.{mod}.Blocks\n')
    print(f'lower {len(lower)}, mid {len(mid)}, top {len(top)} blocks; den7 {den7}; qscale {qscale}', file=sys.stderr)


if __name__ == '__main__':
    main()
