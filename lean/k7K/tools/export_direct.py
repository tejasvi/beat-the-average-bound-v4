#!/usr/bin/env python3
"""Export a direct (k <= 7) certificate of C_6.39 and its extension trees to a Lean data module.

Usage: python3 -I export_direct.py CERT.json TREEDIR K MODNAME OUT.lean [LEVELSMOD]

With LEVELSMOD (e.g. BeatAvg.Data.K8.Trees, whose namespace defines `levels` for the same trees), the trees are not
written: the module imports LEVELSMOD, `levels` is that definition, and `check` uses the array-based `directOKA`.

Reads the certificate (format: cert/README.md of the P4 repository) and trees_4..trees_K (json). Writes a Lean module
with namespace BeatAvg.Data.<MODNAME> defining `levels`, `blocks`, `lamN`, `lamD`, `den`, `qscale` and
`check : Bool := chainOK 3 [0] levels && directOK K blocks lamN lamD den qscale (chainList [0] levels)`.
Nothing in the data is trusted by the Lean proof; the exporter only re-encodes the JSON (no computation is
certified here). The leaves of every tree are recomputed by replaying the tree walk (signs only, no checks).
"""
import sys, json, itertools, math, hashlib


def tuples_of(k):
    T = []
    for j in range(3, k):
        for d in range(j + 1):
            others = [i for i in range(j + 1) if i != d]
            for (a, b, c) in itertools.combinations(others, 3):
                if j in (d, a, b, c):
                    T.append((d, a, b, c))
    return T


def replay_leaves(k, P_bits, perm, tokens):
    """Leaves (as integers over T_k) of one tree, in DFS order (bit 1 subtree first)."""
    npar = len(tuples_of(k - 1))
    n = len(tuples_of(k)) - npar
    out = []
    pos = 0
    assign = {}

    def walk(i):
        nonlocal pos
        if i == n:
            v = P_bits
            for u, b in assign.items():
                if b:
                    v |= 1 << (npar + u)
            out.append(v)
            return
        u = perm[i]
        tok = tokens[pos]; pos += 1
        if tok == 2:
            assign[u] = 1; walk(i + 1)
            assign[u] = 0; walk(i + 1)
            del assign[u]
            return
        c = tokens[pos]; pos += 1
        pos += 2 * c
        assign[u] = tok
        walk(i + 1)
        del assign[u]

    sys.setrecursionlimit(100000)
    walk(0)
    assert pos == len(tokens)
    return out


def pack(fields, w):
    x = 0
    for i, f in enumerate(fields):
        assert 0 <= f < (1 << w), (f, w)
        x |= f << (w * i)
    return x


def zig(z):
    return 2 * z if z >= 0 else -2 * z - 1


def main():
    sys.set_int_max_str_digits(0)
    certfn, treedir, K, modname, outfn = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4], sys.argv[5]
    levmod = sys.argv[6] if len(sys.argv) > 6 else None
    cert = json.load(open(certfn))
    assert cert['K'] == K
    lines = []
    if levmod:
        lines.append(f'import BeatAvg.Core.DirectA\nimport {levmod}\n')
    else:
        lines.append('import BeatAvg.Core.Chain\n')
    lines.append(f'/-! Data generated by tools/export_direct.py from {certfn.split("/")[-1]} '
                 f'(sha256 {hashlib.sha256(open(certfn, "rb").read()).hexdigest()}). -/\n')
    lines.append('set_option maxRecDepth 100000\n')
    lines.append(f'namespace BeatAvg.Data.{modname}\nopen BeatAvg.Check\n')
    parents = [0]
    levnames = []
    for k in (range(4, K + 1) if not levmod else []):
        trees = json.load(open(f'{treedir}/trees_{k}.json'))
        assert len(trees) == len(parents)
        nT = len(tuples_of(k))
        recs = []
        newparents = []
        for P, (perm, tokens) in zip(parents, trees):
            leaves = replay_leaves(k, P, perm, tokens)
            newparents += leaves
            assert max(tokens) < 1024 and max(perm) < 256
            recs.append(f'⟨{P}, {pack(perm, 8)}, {len(perm)}, {pack(tokens, 10)}, {nT}, {pack(leaves, nT)}, {len(leaves)}⟩')
        name = f'recs{k}'
        levnames.append(name)
        lines.append(f'def {name} : List PRec := [\n  ' + ',\n  '.join(recs) + ']\n')
        parents = newparents
        print(f'level {k}: {len(trees)} trees, {len(parents)} patterns', file=sys.stderr)
    if levmod:
        lines.append(f'def levels : List (List TreeRec) := {levmod.rsplit(".", 1)[0]}.levels\n')
    else:
        lines.append('def levels : List (List TreeRec) := [' + ', '.join(f'{n}.map PRec.unpackR' for n in levnames) + ']\n')
    # blocks
    wds = set()
    vdens = set()
    pbs = []
    Ds = []
    for b in cert['blocks']:
        t, m = b['t'], b['m']
        nTm = len(tuples_of(m)) if m >= 4 else 0
        flags = []
        for bits, J in b['flags']:
            assert len(bits) == nTm
            bv = sum(1 << i for i, ch in enumerate(bits) if ch == '1')
            jm = sum(1 << j for j in J)
            flags.append(bv | (jm << nTm))
        n = len(flags)
        terms = []
        maxz = 1
        for wn, wd, v in b['sos']['terms']:
            wds.add(wd)
            assert len(v) == n and wn >= 0
            maxz = max(maxz, max(zig(z) for z in v))
        wv = maxz.bit_length()
        for wn, wd, v in b['sos']['terms']:
            terms.append(f'({wn}, {pack([zig(z) for z in v], wv)})')
        vdens.add(b['sos']['den'])
        pbs.append(f'⟨{t}, {m}, {n}, {nTm}, {pack(flags, nTm + m)}, {wv}, [{", ".join(terms)}]⟩')
        D = math.comb(K, t) * math.comb(K - t, m - t) * math.comb(K - m, m - t)
        Ds.append(D)
    assert len(wds) == 1 and len(vdens) == 1
    qscale = wds.pop() * vdens.pop() ** 2
    nTK = len(tuples_of(K))
    den = nTK
    for D in Ds:
        den = den * (D * qscale) // math.gcd(den, D * qscale)
    lines.append('def pblocks : List PBlock := [\n  ' + ',\n  '.join(pbs) + ']\n')
    lines.append('def blocks : List DBlock := pblocks.map PBlock.unpackB\n')
    lamN, lamD = cert['claimed']
    lines.append(f'def lamN : Nat := {lamN}\ndef lamD : Nat := {lamD}\ndef den : Nat := {den}\ndef qscale : Nat := {qscale}\n')
    chk = 'directOKA' if levmod else 'directOKT'
    lines.append(f'def check : Bool := chainOK 3 [0] levels && {chk} {K} blocks lamN lamD den qscale (chainList [0] levels)\n')
    lines.append(f'end BeatAvg.Data.{modname}\n')
    open(outfn, 'w').write('\n'.join(lines))
    print(f'wrote {outfn}: {sum(len(l) for l in lines)} chars', file=sys.stderr)


if __name__ == '__main__':
    main()
